import { describe, expect, it } from 'vitest'
import { recentSummary } from '../recentLog'

describe('오른쪽 최근 기록 요약', () => {
  it('생산·투자는 그대로, 인구·행복·문화는 바뀐 것만 앞→뒤로', () => {
    const log = [
      '[R1] 한국 도시 건설 (타일 4장)',
      '[R1] 한국 기술 연구: 문자',
      '[R1] 한국 일꾼 2 / 행복 3',
      '[R1] 독일 전사 생산 (망치 3)',
      '[R1] 독일 일꾼 2 / 행복 4',
      '[R2] 한국 문화 +1 (4→5)',
      '[R2] 한국 피라미드에 망치 4 투자',
      '[R2] 한국 일꾼 3 / 행복 3',
      '[R2] 독일 일꾼 2 / 행복 5',
      '[R3] 한국 일꾼 3 / 행복 3',
    ]
    expect(recentSummary(log)).toEqual([
      '[R1] 독일 전사 생산 (망치 3)',
      '[R2] 한국 문화 4→5',
      '[R2] 한국 피라미드에 망치 4 투자',
      '[R2] 한국 인구 2→3',
      '[R2] 독일 행복 4→5',
    ])
  })
})
